def write_json(payload):
    OUT_JSON.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")


def write_csv(payload):
    with OUT_CSV.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["题号", "类型", "分值", "页码", "材料", "题干", "选项A", "选项B", "选项C", "选项D", "答案", "图片"])
        for q in payload["questions"]:
            opts = q.get("options", {})
            writer.writerow([
                q["number"],
                q["type"],
                q["score"],
                q["source_page"],
                q.get("group_prompt", ""),
                q["stem"],
                opts.get("A", ""),
                opts.get("B", ""),
                opts.get("C", ""),
                opts.get("D", ""),
                q["answer"],
                ";".join(q.get("images", [])),
            ])


def write_md(payload):
    lines = [
        f"# {payload['source']['title']}",
        "",
        f"- 题目数：{len(payload['questions'])}",
        f"- 图片数：{len(payload['figures'])}",
        "",
    ]
    for q in payload["questions"]:
        lines.extend([
            f"## 第{q['number']}题",
            "",
            f"- 类型：{q['type']}",
            f"- 分值：{q['score']}",
            f"- 页码：{q['source_page']}",
            f"- 材料：{q.get('group_prompt', '')}",
            f"- 题干：{q['stem']}",
        ])
        for key, value in q.get("options", {}).items():
            lines.append(f"- {key}. {value}")
        lines.extend([
            f"- 答案：{q['answer']}",
            f"- 图片：{', '.join(q.get('images', []))}",
            "",
        ])
    OUT_MD.write_text("\n".join(lines), encoding="utf-8")


def main():
    export_figures()
    payload = build_payload()
    write_json(payload)
    write_csv(payload)
    write_md(payload)
    print(f"Generated {OUT_JSON}")
    print(f"Questions: {len(payload['questions'])}")
    print(f"Figures: {len(payload['figures'])}")


if __name__ == "__main__":
    main()
