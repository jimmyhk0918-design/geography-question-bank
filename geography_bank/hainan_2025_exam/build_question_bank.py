def export_figures() -> list[dict]:
    IMAGES_DIR.mkdir(parents=True, exist_ok=True)
    exported = []
    for figure_id, page, box, caption, question_numbers in FIGURES:
        with Image.open(PAGES_DIR / f"page-{page:02d}.jpeg") as image:
            image.crop(box).save(IMAGES_DIR / f"{figure_id}.png", optimize=True)
        exported.append({"id": figure_id, "page": page, "bbox": list(box), "caption": caption, "questions": question_numbers, "path": f"question_images/{figure_id}.png"})
    return exported


def build_payload() -> dict:
    return {
        "source": {"id": "hainan_2025_exam", "title": "2025年海南省中考地理试题", "year": 2025, "grade": "九年级", "region": "海南省", "question_count": len(QUESTIONS), "total_score": 100},
        "figures": export_figures(),
        "questions": QUESTIONS,
    }


def write_exports(payload: dict) -> None:
    JSON_PATH.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    fields = ["id", "number", "type", "score", "source_page", "topic", "group_prompt", "stem", "options", "answer", "images"]
    with CSV_PATH.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        for question in payload["questions"]:
            row = question.copy()
            row["options"] = " | ".join(f"{key}. {value}" for key, value in row["options"].items())
            row["images"] = " | ".join(row["images"])
            writer.writerow({key: row.get(key, "") for key in fields})
    lines = ["# 2025年海南省中考地理试题题库", "", "- 35道选择题，3道综合题，满分100分。", ""]
    for question in payload["questions"]:
        lines += [f"## 第{question['number']}题（{question['score']}分）", "", question["group_prompt"], "", question["stem"], ""]
        for path in question["images"]:
            lines += [f"![题图]({path})", ""]
        lines += [*(f"{key}. {value}" for key, value in question["options"].items()), "", f"**参考答案：** {question['answer']}", ""]
    MARKDOWN_PATH.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    payload = build_payload()
    write_exports(payload)
    print(f"Built {len(QUESTIONS)} questions and {len(payload['figures'])} figures.")
